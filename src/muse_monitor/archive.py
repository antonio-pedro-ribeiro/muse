"""Session archives: a .zip with one folder per session (session.json, raw/, events.jsonl, derived/, analyses/,
reports/), so recordings can be moved between computers and imported again.

Import is defensive: an archive comes from outside. Paths must stay inside the session folder (no absolute paths,
no "..", no drive letters), sizes and compression ratios are capped, session ids must be plain names, an existing
session is never overwritten, and a session is only added once its files were unpacked and its streams read."""

from __future__ import annotations

import json
import os
import shutil
import uuid
import zipfile
from datetime import UTC, datetime
from pathlib import Path, PurePosixPath
from typing import Any, Callable

from .sdk import storage
from .sdk.types import SessionInfo

MANIFEST = "MUSE-ARCHIVE.json"
SKIP_TOP = {"export"}                       # files generated by Export; recreate them from the raw data
MAX_IMPORT_BYTES = 8 * 2**30                # unpacked size
MAX_RATIO = 200                             # unpacked / packed, above this it looks like a zip bomb


class ArchiveError(ValueError):
    pass


def export_archive(session_dirs: list[Path], out: Path) -> Path:
    """Writes the sessions into `out` (.zip). Parquet is already compressed, so it is stored as is."""
    out.parent.mkdir(parents=True, exist_ok=True)
    tmp = out.with_name(out.name + ".partial")
    with zipfile.ZipFile(tmp, "w", allowZip64=True) as z:
        for d in session_dirs:
            for f in sorted(d.rglob("*")):
                rel = f.relative_to(d)
                if not f.is_file() or rel.parts[0] in SKIP_TOP:
                    continue
                kind = zipfile.ZIP_STORED if f.suffix == ".parquet" else zipfile.ZIP_DEFLATED
                z.write(f, f"{d.name}/{rel.as_posix()}", compress_type=kind)
        z.writestr(MANIFEST, json.dumps({"format": "muse-monitor session archive", "version": 1,
                                         "sessions": [d.name for d in session_dirs],
                                         "created_at": datetime.now(UTC).isoformat()}, indent=2))
    os.replace(tmp, out)
    return out


def bundle(files: dict[str, list[Path]], out: Path) -> Path:
    """Exported files per session -> one download: a lone file as is, else a zip (a folder per session if several)."""
    flat = [f for fs in files.values() for f in fs]
    if len(files) == 1 and len(flat) == 1 and flat[0].suffix != ".csv":
        shutil.copyfile(flat[0], out)
        return out
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED, allowZip64=True) as z:
        for sid, fs in files.items():
            for f in fs:
                z.write(f, f.name if len(files) == 1 else f"{sid}/{f.name}")
    return out


def _roots(infos: list[zipfile.ZipInfo]) -> list[str]:
    """Folder prefixes that hold a session.json: "" (one session at the top) or "<folder>/"."""
    roots = set()
    for i in infos:
        p = PurePosixPath(i.filename)
        if p.name == "session.json" and len(p.parts) <= 2:
            roots.add("" if len(p.parts) == 1 else p.parts[0] + "/")
    return [""] if "" in roots else sorted(roots)


def _safe(rel: str) -> PurePosixPath:
    p = PurePosixPath(rel)
    if not rel or p.is_absolute() or ".." in p.parts or ":" in rel or "\\" in rel:
        raise ArchiveError(f"unsafe path in archive: {rel!r}")
    return p


def import_archive(path: Path, data_dir: Path, check_id: Callable[[str], str]) -> dict[str, Any]:
    """Unpacks every session in the archive into `data_dir`. Returns {"imported": [...], "skipped": [...]}."""
    try:
        z = zipfile.ZipFile(path)
    except (zipfile.BadZipFile, OSError) as exc:
        raise ArchiveError(f"not a zip archive: {exc}") from exc
    imported: list[dict[str, Any]] = []
    skipped: list[dict[str, str]] = []
    with z:
        infos = z.infolist()
        unpacked = sum(i.file_size for i in infos)
        packed = sum(i.compress_size for i in infos) or 1
        if unpacked > MAX_IMPORT_BYTES:
            raise ArchiveError(f"archive unpacks to {unpacked / 2**30:.1f} GB, more than the "
                               f"{MAX_IMPORT_BYTES / 2**30:.0f} GB limit")
        if unpacked > 100 * 2**20 and unpacked / packed > MAX_RATIO:
            raise ArchiveError("archive compression ratio is implausibly high; refusing to unpack it")
        for i in infos:                                       # a crafted path rejects the whole archive, up front
            _safe(i.filename.rstrip("/") if i.is_dir() else i.filename)
        roots = _roots(infos)
        if not roots:
            raise ArchiveError("no sessions found: expected <session id>/session.json inside the archive")
        data_dir.mkdir(parents=True, exist_ok=True)
        for root in roots:
            where = root.rstrip("/") or "(top level)"
            try:
                info = SessionInfo.model_validate_json(z.read(root + "session.json"))
                sid = check_id(info.id)
            except Exception as exc:                      # invalid metadata or id: skip this one
                skipped.append({"session": where, "reason": f"invalid session.json: {exc}"[:300]})
                continue
            if info.mode != "live":
                skipped.append({"session": sid, "reason": "not a recording (an analysis entry)"})
                continue
            dest = data_dir / sid
            if dest.exists():
                skipped.append({"session": sid, "reason": "already exists here"})
                continue
            tmp = data_dir / f".import-{uuid.uuid4().hex}"
            try:
                for i in infos:
                    if i.is_dir() or not i.filename.startswith(root) or i.filename == MANIFEST:
                        continue
                    rel = _safe(i.filename[len(root):])
                    target = tmp.joinpath(*rel.parts)
                    target.parent.mkdir(parents=True, exist_ok=True)
                    with z.open(i) as src, open(target, "wb") as dst:
                        shutil.copyfileobj(src, dst, 1 << 20)
                streams = [s for s in storage.list_streams(tmp) if "/" not in s.id]
                if not streams:
                    raise ArchiveError("no recorded data (raw/*.parquet) in this session")
                os.replace(tmp, dest)
                imported.append({"id": sid, "label": info.label, "started_at": info.started_at.isoformat(),
                                 "streams": [s.id for s in streams]})
            except Exception as exc:
                shutil.rmtree(tmp, ignore_errors=True)
                skipped.append({"session": sid, "reason": str(exc)[:300]})
    return {"imported": imported, "skipped": skipped}
